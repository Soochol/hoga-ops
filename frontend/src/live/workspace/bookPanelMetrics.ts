/**
 * BookPanel(10호가 십자 배치)의 **폭 계약** — `/live` 와 `/study` 가 공유하는 SSOT.
 *
 * 이 값은 컴포넌트 밖에서도 load-bearing 이다. 창 좌표가 비율(0~1)이라 절대 하한을
 * 표현하지 못하므로(ADR-0122), 기본 배치 비율과 새 창 기본 크기는 **이 하한에서
 * 역산**된다 — `state/workspace.ts` · `state/studyWorkspace.ts` 가 그 소비처다.
 * 2026-08-16 이전엔 같은 숫자(560)가 소스 3곳 + 테스트 2곳에 흩어져 있었고, 한
 * 곳만 고치면 나머지가 조용히 어긋났다.
 *
 * ⚠ **Tailwind 임의값(`min-w-[455px]`)으로 되돌리지 말 것.** JIT 는 빌드 타임에
 * 리터럴을 스캔하므로 `min-w-[${C}px]` 같은 보간은 클래스가 생성되지 않고 하한이
 * **에러 없이 사라진다**. 상수를 쓰려면 인라인 style 이어야 한다.
 *
 * ## 폭 예산 (2026-08-16 /browse 실측, 1.0× 밀도 다이얼 기준)
 *
 * 최악 케이스 = 고가 7자리 종목(삼성바이오로직스급). 열별 콘텐츠 필요 폭:
 *
 * | 열                          | 최악 콘텐츠                       | 필요 |
 * |-----------------------------|-----------------------------------|-----:|
 * | 좌(잔량바·체결강도·체결)     | `1,319,000` + `1,234,567`         |  132 |
 * | 중앙(가격축)                 | `1,319,000` + `+30.00%`(7ch)      |  113 |
 * | 우(요약·매수바)              | `250일 1,319,000/1,081,100`       |  178 |
 * | **합**                       |                                   |  **423** |
 *
 * 448 은 그 위 25px 이었다. 종전 560 은 137px(24.5%) 이 슬랙이었고, 그 슬랙이 우측
 * 통계의 라벨↔값 간격을 벌려 빈 세로 띠로 보였다(2026-07-24 에 680→600 으로 한 번
 * 줄인 것의 연장선). 폰트를 줄인 것이 **아니다** — `DESIGN.md` 의 밀도 다이얼은 이미
 * 최소단(1.0×)이라 축소분은 전부 열 배분에서 나왔다.
 *
 * ## 2026-08-18: 중앙 열을 +10% 하며 하한을 재유도했다 (448 → 455)
 *
 * 사용자 요청은 "가격 영역을 좌우 5%씩" — 중앙 상한 126 → 139(좌우 각 +6.5px)다.
 * 하한은 그 상한에서 **다시 유도된다**: 132(좌 최악) + 139 + 184 = 455. 448 을 그대로
 * 두면 7px 이 모자라 최악 종목 × 최소폭에서 가로 스크롤이 났다 — 즉 이 파일에서
 * 중앙 상한만 고치는 것은 성립하지 않는다. 새 배분에서 좌측 슬랙은 0 이다(종전 +6):
 * 좌측은 잘려도 한 행이 짧아질 뿐이라는 아래 "실패 비용" 논리에 따라 그 6px 을
 * 중앙에 넘겼다.
 *
 * 그 슬랙 0 을 도그푸딩으로 재검증했다(삼성바이오로직스 207940, 가격 `1,541,000` +
 * 좌측 잔량을 `1,234,567` 로 치환한 최악 조합):
 *
 *   - 좌측 min-content **130** ≤ 할당 132 → 잘림·개행 없음(전 22행 높이 22px 유지)
 *   - 455px 에서 `scrollWidth − clientWidth = 0`
 *   - 같은 화면을 448px 로 좁히면 **정확히 7px** — 하한을 안 올렸을 때의 실패다
 *
 * 이 아래로 좁히면 설계대로 **가로 스크롤**이 생긴다(겹치거나 잘리지 않는다).
 * 요약 행이 개행되어 11행 정렬 계약(우측 요약 11행 = 매수 잔량 바 정렬)이 깨지는
 * 것보다 스크롤이 싸다 — `BookPanel` 의 `SummaryRow` nowrap 주석 참조.
 */
export const BOOK_PANEL_MIN_W = 455;

/**
 * 3열 트랙 — 좌(잔량바·체결) / 중앙(가격축) / 우(요약·매수바).
 *
 * `BOOK_PANEL_MIN_W` 에서의 배분은 **132 / 139 / 184** 로 위 표의 필요 폭을 각각
 * +0 / +26 / +6 넘긴다.
 *
 * **중앙 상한은 선택이 아니라 제약이다.** `minmax()` 의 상한은 `fr` 보다 먼저 채워지고
 * `fr` 트랙은 min-content 아래로 줄지 않으므로, 상한을 올린 만큼 하한도 같이 올리지
 * 않으면 최소폭에서 좌측이 굶어 가로 스크롤이 난다(2026-08-16 실측: 중앙 상한 180 을
 * 448 에 그대로 두었을 때 gridScrollWidth 462 > 448).
 *
 * **하한 112 는 사실상 dormant 하다** — 상한이 `fr` 분배보다 먼저 차므로 `MIN_W` 이상
 * 어느 폭에서도 중앙은 상한에 붙어 있다(2026-08-18 실측: 493px 창 170/139/184 ·
 * 470px 창 147/139/184 · 하한 455px 132/139/184).
 * 남는 폭은 전부 좌측으로 흘러 깊이 막대가 길어진다 — 가격 숫자는 중앙 정렬이라
 * 열 폭이 달라져도 x 가 흔들리지 않는다.
 *
 * 우측 하한이 좌측보다 큰 이유는 콘텐츠가 아니라 **실패 비용**이다: 좌측은 잘려도
 * 한 행이 짧아질 뿐이지만, 우측 요약이 밀리면 11행 계약을 통해 매수 잔량 바 전체의
 * 세로 정렬이 어긋난다.
 */
export const BOOK_PANEL_GRID_COLS = '1fr minmax(112px,139px) minmax(184px,1fr)';

